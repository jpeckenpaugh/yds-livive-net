/**
 * The conversation registry — the single place `src/ui/**` gets content from
 * (D6 §2.1, amendment F1).
 *
 * Each entry is a **generated** artifact produced by `npm run bake:content`
 * (content) or `npm run bake:fixture` (the M1 fixture). Adding a conversation is
 * an import plus an array entry; nothing in the UI changes.
 *
 * All artifacts are imported statically, so they all ship in the bundle. With
 * five conversations that is a few tens of KB gzipped; if the catalog grows past
 * that, this is the seam to make lazy (`import()` per conversation, with the
 * catalog holding only metadata).
 */

import type { Conversation } from '../domain/types.ts';
import cafeOrder from './conversations/cafe-order.json';
import clothesShopping from './conversations/clothes-shopping.json';
import gettingThere from './conversations/getting-there.json';
import fixture from './conversations/m1-fixture.json';
import notFeelingWell from './conversations/not-feeling-well.json';

const artifacts: unknown[] = [
  // The M1 fixture: placeholder content that proves the pipeline. Deleted in M2.
  fixture,
  // Content conversations, generated by `npm run bake:content`.
  clothesShopping,
  cafeOrder,
  gettingThere,
  notFeelingWell,
];

export const CONVERSATIONS: Conversation[] = artifacts as Conversation[];

export function conversationById(id: string): Conversation | undefined {
  return CONVERSATIONS.find((entry) => entry.id === id);
}
